"""Self-host the site's web fonts.

Downloads the Google Fonts files the site uses into /fonts and writes
css/fonts.css (Latin, every page) and css/fonts-zh.css (Chinese pages).
Chinese fonts are split by Google into ~100 slices per family; only the
slices that contain characters used on the zh pages are kept. Re-run after
changing Chinese copy:  python3 tools/build_fonts.py
"""
import html, pathlib, re, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/126.0 Safari/537.36')
LATIN = ('https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,400..700;'
         '1,9..144,400..700&family=Hanken+Grotesk:wght@400;500;600;700&family=DM+Mono:wght@400;500'
         '&display=swap')
ZH = ('https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@400;500;700'
      '&family=Noto+Serif+SC:wght@600;700&display=swap')
KEEP_LATIN = {'latin', 'latin-ext'}


def get(url):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req) as r:
        return r.read()


def faces(css):
    """Yield (subset label, @font-face block) pairs. Chinese slices have no label."""
    for m in re.finditer(r'(?:/\*\s*([^*]+?)\s*\*/\s*)?(@font-face\s*{[^}]*})', css):
        yield m.group(1) or '', m.group(2)


def ranges(block):
    spec = re.search(r'unicode-range:\s*([^;]+);', block).group(1)
    for part in spec.split(','):
        part = part.strip()[2:]
        lo, _, hi = part.partition('-')
        if '?' in lo:
            yield int(lo.replace('?', '0'), 16), int(lo.replace('?', 'F'), 16)
        else:
            yield int(lo, 16), int(hi or lo, 16)


def zh_chars():
    text = ''
    for f in (ROOT / 'zh').glob('*.html'):
        src = f.read_text(encoding='utf-8')
        text += html.unescape(re.sub(r'<[^>]+>', ' ', src))
    text += (ROOT / 'js' / 'site.js').read_text(encoding='utf-8')
    return {ord(c) for c in text if ord(c) > 0x2000}


def localise(css, keep):
    out, fonts = [], ROOT / 'fonts'
    fonts.mkdir(exist_ok=True)
    for label, block in faces(css):
        if not keep(label, block):
            continue
        url = re.search(r'url\((https://fonts\.gstatic\.com/[^)]+)\)', block).group(1)
        name = re.sub(r'^https://fonts\.gstatic\.com/s/', '', url).replace('/', '-')
        dest = fonts / name
        if not dest.exists():
            dest.write_bytes(get(url))
        out.append((f'/* {label} */\n' if label else '') + block.replace(url, f'/fonts/{name}'))
    return out


def main():
    head = '/* Generated by tools/build_fonts.py. Do not edit by hand. */\n'
    latin = localise(get(LATIN).decode(), lambda label, _: label in KEEP_LATIN)
    (ROOT / 'css' / 'fonts.css').write_text(head + '\n'.join(latin) + '\n', encoding='utf-8')

    used = zh_chars()
    def wanted(label, block):
        if label:
            return False  # Latin/Cyrillic subsets: Latin text uses the Latin fonts
        return any(lo <= c <= hi for lo, hi in ranges(block) for c in used)
    zh = localise(get(ZH).decode(), wanted)
    (ROOT / 'css' / 'fonts-zh.css').write_text(head + '\n'.join(zh) + '\n', encoding='utf-8')

    referenced = set(re.findall(r'/fonts/([^)]+)\)', '\n'.join(latin + zh)))
    for f in (ROOT / 'fonts').glob('*.woff2'):
        if f.name not in referenced:
            f.unlink()
    print(f'latin faces: {len(latin)}, zh faces: {len(zh)}, files: {len(referenced)}')


if __name__ == '__main__':
    main()
